def fmt_inr(n):
    """Indian digit grouping: 120000 -> '₹1,20,000'."""
    n = int(round(n))
    s = str(abs(n))
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        s = ",".join(groups) + "," + tail
    return ("-" if n < 0 else "") + "₹" + s


def _snap(t, x):
    x = round((x - t["lo"]) / t["step"]) * t["step"] + t["lo"]
    return int(min(t["hi"], max(t["lo"], x)))


def value_2025(topic, tier, zone):
    t = TOPICS[topic]
    q = TIER_INDEX[tier]
    if topic in NOT_COVERED_FOR_BRONZE and tier == "bronze":
        return 0
    if topic == "copay_pct":
        return TIER_COPAY[q] + ZONE_COPAY[zone]
    frac = TIER_FRACTION[q]
    base = t["lo"] + frac * (t["hi"] - t["lo"]) if t["better"] == "high" else t["hi"] - frac * (t["hi"] - t["lo"])
    r = random.Random(f"{SEED}|{topic}|{tier}|{zone}")
    return _snap(t, base + t["step"] * r.randint(-1, 1))


def unchanged_topics(tier, zone):
    """Two topics keep their 2024 value; the rest change (bronze also keeps its zero topics)."""
    r = random.Random(f"{SEED}|unchanged|{tier}|{zone}")
    return set(r.sample(sorted(set(TOPICS) - NOT_COVERED_FOR_BRONZE - {"copay_pct"}), 2))


def make_value(topic, tier, zone, year):
    v = value_2025(topic, tier, zone)
    if year == CURRENT_YEAR or v == 0 and topic in NOT_COVERED_FOR_BRONZE or topic in unchanged_topics(tier, zone):
        return v
    t = TOPICS[topic]
    r = random.Random(f"{SEED}|2024|{topic}|{tier}|{zone}")
    d = t["step"] * r.randint(1, 2)
    old = v - d if v - d >= t["lo"] else v + d
    if old == 0 and topic in NOT_COVERED_FOR_BRONZE:
        old = v + d
    return int(min(t["hi"], old))


def make_extra(topic, tier, zone, year):
    lo, hi, step, _ = TOPICS[topic]["cond"]
    r = random.Random(f"{SEED}|extra|{topic}|{tier}|{zone}|{year}")
    return lo + step * r.randint(0, (hi - lo) // step)


def show(topic, v):
    return fmt_inr(v) if TOPICS[topic]["money"] else str(v)


def doc_id_for(topic, tier, zone, year):
    return f"BEN-{tier.upper()}-{zone}-{year}-{topic}"


def plan_header(tier, zone, year):
    return (f"Plan tier: {TIERS[tier]} | Zone: {zone} ({ZONES[zone]}) | Plan year: {year} | "
            f"Status: {YEARS[year]['status']}")


def render_benefit(topic, tier, zone, year):
    t, y = TOPICS[topic], YEARS[year]
    doc_id = doc_id_for(topic, tier, zone, year)
    value = make_value(topic, tier, zone, year)
    extra = make_extra(topic, tier, zone, year)
    covered = value != 0 or not (topic in NOT_COVERED_FOR_BRONZE)
    if covered:
        entitlement = t["sent"].format(v=show(topic, value))
        x = fmt_inr(extra) if topic in CONDITION_IN_RUPEES else str(extra)
        conditions = t["cond"][3].format(x=x)
    else:
        entitlement = f"{t['title']} is not covered on the {TIERS[tier]} plan."
        conditions = "No conditions apply."
    version_note = ("This is the current version. It replaced the 2024 version." if y["status"] == "CURRENT"
                    else "This version was replaced on 2025-01-01 and must not be used for current claims.")
    text = (
        f"PLAN BENEFIT DOCUMENT {doc_id}\n"
        f"Title: {t['title']}\n"
        f"{plan_header(tier, zone, year)}\n"
        f"Effective from: {y['start']} | Effective until: {y['end']}\n"
        f"Version note: {version_note}\n\n"
        f"1. Scope\nThis document sets out the {t['title'].lower()} for Asteria Health {TIERS[tier]} plan "
        f"members in zone {zone} ({ZONES[zone]}).\n\n"
        f"2. Entitlement\n{entitlement}\n\n"
        f"3. Conditions\n{conditions}\n\n"
        f"4. Exclusions\n{EXCLUSIONS}\n"
    )
    meta = dict(doc_id=doc_id, kind="benefit", topic=topic, title=t["title"], tier=tier, zone=zone,
                year=year, status=y["status"])
    fact = dict(doc_id=doc_id, topic=topic, tier=tier, zone=zone, year=year, status=y["status"],
                value=value, unit=t["unit"], covered=covered, extra=extra)
    return meta, text, fact


